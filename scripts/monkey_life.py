# ---------------------------------------------------------------- character
def head(eyes="open", tilt=0, bob=False):
    """Head at local origin = head centre, facing right."""
    if eyes == "open":
        eye_parts = ""
        for ex in (-1, 7):
            eye_parts += (
                f'<ellipse cx="{ex}" cy="-1" rx="2.6" ry="3.2" fill="#fff"/>'
                f'<circle cx="{ex + 0.8}" cy="-0.6" r="1.5" fill="{DARK}"/>'
                f'<circle cx="{ex + 1.4}" cy="-1.4" r="0.55" fill="#fff"/>'
            )
        # slow blink
        eye_parts += (
            f'<g fill="{SKIN}"><rect x="-5" y="-5" width="16" height="0" rx="2">'
            f'<animate attributeName="height" values="0;0;8;0;0" keyTimes="0;0.9;0.94;0.98;1" '
            f'dur="6s" repeatCount="indefinite"/></rect></g>'
        )
    else:
        eye_parts = (
            f'<path d="M -3.4,-1 q 2.4,2.2 4.8,0" fill="none" stroke="{DARK}" stroke-width="1.1" stroke-linecap="round"/>'
            f'<path d="M 4.6,-1 q 2.4,2.2 4.8,0" fill="none" stroke="{DARK}" stroke-width="1.1" stroke-linecap="round"/>'
        )
    bob_anim = (
        '<animateTransform attributeName="transform" type="translate" '
        'values="0,0;0,1.6;0,0" dur="1.1s" repeatCount="indefinite" additive="sum"/>'
        if bob else ""
    )
    return (
        f'<g transform="rotate({tilt})">{bob_anim}'
        f'<circle cx="-12" cy="-3" r="6" fill="{FUR}"/><circle cx="-12" cy="-3" r="3" fill="{SKIN_D}"/>'
        f'<circle cx="12" cy="-3" r="6" fill="{FUR}"/><circle cx="12" cy="-3" r="3" fill="{SKIN_D}"/>'
        f'<circle cx="0" cy="0" r="13" fill="{FUR}"/>'
        f'<path d="M -10,-8 q 10,-7 20,0 q -4,-3 -10,-3 q -6,0 -10,3 z" fill="{FUR_D}" opacity="0.6"/>'
        f'<ellipse cx="3" cy="3.5" rx="9.5" ry="8" fill="{SKIN}"/>'
        + eye_parts +
        f'<circle cx="5" cy="4.6" r="0.8" fill="{FUR_D}"/><circle cx="7.4" cy="4.6" r="0.8" fill="{FUR_D}"/>'
        f'<path d="M 2,8 q 4.5,3.4 9,0" fill="none" stroke="{FUR_D}" stroke-width="1.2" stroke-linecap="round"/>'
        f"</g>"
    )


def tail(base=(-13, -26), sway=10, dur=3.2):
    bx, by = base
    return (
        f'<g transform="translate({bx},{by})">'
        f'<animateTransform attributeName="transform" type="rotate" '
        f'values="-{sway} 0 0;{sway} 0 0;-{sway} 0 0" dur="{dur}s" repeatCount="indefinite" additive="sum"/>'
        f'<path d="M 0,0 C -16,-2 -26,-18 -18,-30 C -14,-36 -6,-36 -6,-30" '
        f'fill="none" stroke="{FUR}" stroke-width="6.5" stroke-linecap="round"/></g>'
    )


def limb(x, y, angle, length=20, width=7, color=FUR, swing=None):
    """Capsule limb hung from (x, y), rotated `angle`° from straight down."""
    anim = (
        f'<animateTransform attributeName="transform" type="rotate" '
        f'values="{swing[0]} 0 0;{swing[1]} 0 0;{swing[0]} 0 0" dur="{swing[2]}s" '
        f'repeatCount="indefinite" additive="sum"/>'
        if swing else ""
    )
    return (
        f'<g transform="translate({x},{y}) rotate({angle})">{anim}'
        f'<path d="M 0,0 Q 1.5,{length * 0.55} 0,{length}" fill="none" '
        f'stroke="{color}" stroke-width="{width}" stroke-linecap="round"/>'
        f'<circle cx="0" cy="{length}" r="{width * 0.52}" fill="{SKIN_D}"/></g>'
    )


def body():
    return (
        f'<ellipse cx="0" cy="-26" rx="15" ry="19" fill="{FUR}"/>'
        f'<ellipse cx="3" cy="-22" rx="9.5" ry="12.5" fill="{SKIN_D}"/>'
    )


def monkey_sit(eat=False, arms_up=False, eyes="open"):
    """Sitting monkey, origin at seat/ground."""
    arm_back = limb(-6, -38, 18, 19)
    if eat:
        # right arm pumps banana to mouth
        arm_front = (
            f'<g transform="translate(7,-38)">'
            f'<animateTransform attributeName="transform" type="rotate" '
            f'values="-118 0 0;-150 0 0;-118 0 0" dur="1.1s" repeatCount="indefinite" additive="sum"/>'
            f'<path d="M 0,0 Q 1.5,10 0,19" fill="none" stroke="{FUR}" stroke-width="7" stroke-linecap="round"/>'
            f'<g transform="translate(0,21) rotate(40)">'
            f'<path d="M -5,0 Q 0,-5 5,0 Q 0,2.5 -5,0 z" fill="#f5d547" stroke="#caa92f" stroke-width="0.7"/></g></g>'
        )
        head_g = f'<g transform="translate(5,-54)">{head(eyes=eyes, bob=True)}</g>'
    elif arms_up:
        arm_front = limb(7, -38, -150, 19, swing=(-8, 8, 0.9))
        arm_back = limb(-6, -38, 150, 19, swing=(8, -8, 0.9))
        head_g = f'<g transform="translate(5,-54)">{head(eyes=eyes)}</g>'
    else:
        arm_front = limb(7, -38, 8, 19)
        head_g = f'<g transform="translate(5,-54)">{head(eyes=eyes)}</g>'
    legs = (
        f'<path d="M -4,-12 Q 8,-14 14,-6 Q 16,-2 12,-1 Q 2,-4 -4,-6 z" fill="{FUR_D}"/>'
        f'<circle cx="13" cy="-3" r="3.6" fill="{SKIN_D}"/>'
    )
    return tail() + arm_back + body() + legs + arm_front + head_g


def monkey_lie():
    """Asleep on his side — whole sitting pose laid down, chest rising."""
    return (
        f'<g transform="rotate(-84) translate(6,2)">'
        f'<animateTransform attributeName="transform" type="scale" values="1;1.025;1" '
        f'dur="4s" repeatCount="indefinite" additive="sum"/>'
        + monkey_sit(eyes="closed") +
        f"</g>"
    )


def monkey_hang():
    """Hanging by both arms (for the vine), origin at the grip point."""
    return (
        f'<g>'
        f'{limb(-5, 2, 168, 20)}{limb(5, 2, 192, 20)}'
        f'<g transform="translate(0,38)">'
        f'<ellipse cx="0" cy="-14" rx="13" ry="17" fill="{FUR}"/>'
        f'<ellipse cx="2" cy="-11" rx="8" ry="11" fill="{SKIN_D}"/>'
        f'{limb(-5, -2, 28, 16)}{limb(6, -2, -20, 16)}'
        f'<g transform="translate(-11,-6)"><path d="M 0,0 C -12,4 -20,-6 -14,-16" fill="none" stroke="{FUR}" stroke-width="6" stroke-linecap="round">'
        f'</path></g>'
        f'<g transform="translate(2,-36)">{head()}</g>'
        f"</g></g>"
    )


def monkey_run():
    """Galloping profile, origin at ground under the chest."""
    return (
        f'<g transform="rotate(14)">'
        + tail(base=(-16, -30), sway=6, dur=0.8)
        + limb(-8, -34, 40, 20, swing=(28, -34, 0.42))
        + f'<ellipse cx="0" cy="-30" rx="17" ry="14" fill="{FUR}"/>'
        f'<ellipse cx="3" cy="-27" rx="10" ry="8.5" fill="{SKIN_D}"/>'
        + limb(-10, -22, -30, 18, swing=(-26, 30, 0.42))
        + limb(9, -22, 24, 18, swing=(30, -26, 0.42))
        + limb(10, -34, -36, 20, swing=(-30, 28, 0.42))
        + f'<g transform="translate(17,-44) rotate(-14)">{head(bob=True)}</g>'
        f"</g>"
    )


def monkey_jump():
    """Stretched mid-leap, origin at chest."""
    return (
        f'<g transform="rotate(-18)">'
        + tail(base=(-15, 2), sway=14, dur=1.4)
        + limb(-12, -4, 130, 20)
        + limb(-8, -8, 118, 20)
        + f'<ellipse cx="0" cy="-8" rx="17" ry="13" fill="{FUR}"/>'
        f'<ellipse cx="3" cy="-6" rx="10" ry="8" fill="{SKIN_D}"/>'
        + limb(10, -14, -118, 20)
        + limb(13, -10, -132, 20)
        + f'<g transform="translate(19,-22) rotate(10)">{head()}</g>'
        f"</g>"
    )


