def scene_for(act, t1, t2, night):
    x1, y1 = t1
    x2, y2 = t2
    mid = (x1 + x2) / 2

    if act == "sleeping":
        zs = "".join(
            f'<text x="{x1 + 64 + i * 13}" y="{GROUND_Y - 40 - i * 7}" font-size="{12 + i * 4}" '
            f'fill="#cdd9f0" font-family="ui-monospace, monospace" opacity="0">z'
            f'<animate attributeName="opacity" values="0;0.9;0" dur="3.2s" begin="{i * 1.05:.1f}s" repeatCount="indefinite"/>'
            f'<animate attributeName="y" values="{GROUND_Y - 32 - i * 7};{GROUND_Y - 64 - i * 7}" dur="3.2s" begin="{i * 1.05:.1f}s" repeatCount="indefinite"/></text>'
            for i in range(3)
        )
        return f'<g transform="translate({x1 + 46},{GROUND_Y - 2})">{monkey_lie()}</g>' + zs

    if act == "eating":
        peels = (
            f'<g transform="translate({mid - 24},{GROUND_Y - 2})">'
            f'<path d="M -6,0 Q 0,-6 6,0 Q 0,2.6 -6,0 z" fill="#f5d547" transform="rotate(-14)"/>'
            f'<path d="M 4,3 Q 10,-3 16,3 Q 10,5.4 4,3 z" fill="#f0c93a"/></g>'
        )
        return peels + f'<g transform="translate({mid + 10},{GROUND_Y - 2})">{monkey_sit(eat=True)}</g>'

    if act == "swinging":
        vine_color = "#3c5a3c" if night else "#4a7a4a"
        return (
            f'<path d="M {x1},{y1} Q {mid},{y1 + 150} {x2},{y2}" fill="none" '
            f'stroke="{vine_color}" stroke-width="3.4" stroke-linecap="round"/>'
            f'<g>{monkey_hang()}'
            f'<animateMotion dur="5.4s" repeatCount="indefinite" keyPoints="0;1;0" keyTimes="0;0.5;1" '
            f'calcMode="linear" path="M {x1},{y1 + 4} Q {mid},{y1 + 150} {x2},{y2 + 4}"/></g>'
        )

    if act == "running":
        return (
            f'<g>{monkey_run()}'
            f'<animateMotion dur="7s" repeatCount="indefinite" keyPoints="0;1;0" keyTimes="0;0.5;1" '
            f'calcMode="linear" path="M {x1 + 40},{GROUND_Y - 2} '
            f'q 45,-22 90,0 q 45,-22 90,0 q 45,-22 90,0 q 45,-22 90,0 q 45,-22 90,0 q 45,-22 90,0"/></g>'
        )

    if act == "playing":
        balls = "".join(
            f'<g><path d="M -5,0 Q 0,-5 5,0 Q 0,2.5 -5,0 z" fill="#f5d547" stroke="#caa92f" stroke-width="0.6"/>'
            f'<animateMotion dur="1.7s" begin="{i * 0.57:.2f}s" repeatCount="indefinite" '
            f'path="M {mid - 22},{GROUND_Y - 78} a 22,30 0 1 1 44,0 a 22,30 0 1 1 -44,0"/></g>'
            for i in range(3)
        )
        return f'<g transform="translate({mid},{GROUND_Y - 2})">{monkey_sit(arms_up=True)}</g>' + balls

    # jumping
    return (
        f'<g>{monkey_jump()}'
        f'<animateMotion dur="5.6s" repeatCount="indefinite" '
        f'keyPoints="0;0.45;0.5;0.95;1" keyTimes="0;0.4;0.5;0.9;1" calcMode="linear" '
        f'path="M {x1},{y1 - 20} Q {mid},{y1 - 120} {x2},{y2 - 20} Q {mid},{y2 - 120} {x1},{y1 - 20}"/></g>'
    )


