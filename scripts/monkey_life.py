def pick_activity(hour):
    if hour >= 22 or hour < 6:
        return "sleeping"
    if hour < 8:
        return "eating"
    if hour < 11:
        return "swinging"
    if hour < 13:
        return "eating"
    if hour < 16:
        return "running"
    if hour < 19:
        return "playing"
    return "jumping"


def bananas_today():
    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        return None
    query = """
    query($login: String!) {
      user(login: $login) {
        contributionsCollection {
          contributionCalendar { weeks { contributionDays { contributionCount date } } }
        }
      }
    }"""
    try:
        req = urllib.request.Request(
            "https://api.github.com/graphql",
            data=json.dumps({"query": query, "variables": {"login": USER}}).encode(),
            headers={"Authorization": f"Bearer {token}", "User-Agent": "rohi/2.0"},
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.load(resp)
        days = [
            d
            for w in data["data"]["user"]["contributionsCollection"]["contributionCalendar"]["weeks"]
            for d in w["contributionDays"]
        ]
        today = datetime.datetime.now(zoneinfo.ZoneInfo("America/New_York")).date().isoformat()
        return next((d["contributionCount"] for d in days if d["date"] == today), 0)
    except Exception:
        return None


def main():
    now = datetime.datetime.now(zoneinfo.ZoneInfo("America/New_York"))
    act = os.environ.get("ROHI_ACT") or pick_activity(now.hour)
    fed = bananas_today()

    sky_svg, night = sky(now.hour)
    t1_svg, t1 = tree(140, night, 1.0)
    t2_svg, t2 = tree(760, night, 0.94)

    status = f"Rohi is {ACTIVITIES[act]} · {now.strftime('%-I:%M %p')} in Charlotte"
    if fed is not None:
        status += f" · fed {fed} 🍌 today" if fed else " · hungry — a git push feeds him 🍌"

    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
        f'role="img" aria-label="Rohi the monkey, currently {ACTIVITIES[act]}">'
        + sky_svg
        + backdrop(night)
        + ground(night)
        + t1_svg
        + t2_svg
        + plants(night)
        + ("" if night else butterfly())
        + scene_for(act, t1, t2, night)
        + f'<text x="{W / 2}" y="{H - 11}" font-size="13" text-anchor="middle" '
        f'fill="{"#cdd9f0" if night else "#eaf7ec"}" font-family="ui-monospace, monospace">{status}</text>'
        + "</svg>"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(svg)
    print(f"monkey-life.svg written — {act} at {now:%H:%M %Z}, fed={fed}")


if __name__ == "__main__":
    main()
